.type Reset_Handler, %function
.thumb_func
Reset_Handler:
    LDR R0, =_sidata
    LDR R1, =_sdata
    LDR R3, =_edata
    CMP R1, R3
    BHS end_data

    copy_loop:
        LDR R2, [R0], #4
        STR R2, [R1], #4
        CMP R1, R3
        BLO copy_loop

    end_data:

    LDR R4, =_sbss
    LDR R5, =_ebss
    MOVS R6, #0
    CMP R4, R5
    BHS end_bss

    set_null:
        STR R6, [R4], #4
        CMP R4, R5
        BLO set_null


    end_bss:
    bl main
    b .

